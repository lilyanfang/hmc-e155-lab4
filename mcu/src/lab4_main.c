#define CLK_FRQ 4000000 //frequency of input clock to TIM7
#define MUSIC notes
#define OUTPUT 4 //output to PB4



int main(void) {
    configureClock(); //turn on MSI clock
    configureTIM6();
    configureTIM7();
    RCC->AHB2ENR |= (1<<1);
    pinMode(OUTPUT,GPIO_OUTPUT);


    int length = sizeof(MUSIC)/sizeof(MUSIC[0]); //number of instructions in notes

    for (int i=0; i<length; i++) {
        int freq = MUSIC[i][0];
        bool rest = !(freq); 
        uint16_t count= CLK_FRQ/(2*freq); //calculate what the count has to be
        TIM7->ARR = count-1; //account for indexing starting at 0
        for (int t=MUSIC[i][1]; t>0; t--) {
            TIM6->CNT=0; //set counter to zero
            TIM6->SR=0; //reset flag to zero
            while (!(TIM6->SR)) {
                if (rest) {
                }
                else if (TIM7->SR) {
                    TIM7->SR = 0;
                    togglePin(OUTPUT);
                }
            } //while counting up do nothing
            //when flag reset
        }
    }
}
